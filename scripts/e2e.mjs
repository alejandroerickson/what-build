// Drive the real UI through the loop against a running `pnpm dev`: node scripts/e2e.mjs
import { chromium } from "playwright-core";
import { writeFileSync, mkdirSync } from "node:fs";

const base = process.argv[2] ?? "http://localhost:5273";
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
const step = (s) => console.log("✓", s);

await page.goto(`${base}/signin`);
await page.getByRole("button", { name: /Sam Okafor/ }).click();
await page.waitForURL((u) => u.pathname === "/");
await page.getByRole("heading", { name: "WhatBuild", exact: true }).waitFor();
step("signed in as an editor, onto the overview");
await page.getByRole("navigation", { name: /Crewboard/ }).getByRole("link", { name: /^Idea/ }).click();
await page.waitForURL(/idea/);
step("opened the sample product's Idea from the overview");
const app = page.url().replace(/\/idea.*$/, "");

await page.goto(`${app}/evidence/new`);
await page.getByLabel("Title").fill("Dispatcher interview — Brightway Cleaning, Sep 2026");
await page.getByLabel(/^Date/).fill("2026-09-10");
await page.getByRole("textbox", { name: /^Tags/ }).fill("brightway cleaning");
await page.getByRole("button", { name: "Add the tag interview" }).click();
await page.getByRole("button", { name: "Continue" }).click();
mkdirSync(".what-build/walkthrough", { recursive: true });
writeFileSync(".what-build/walkthrough/dispatch.txt", "Interviewer: How do crews learn their day?\nJo: A group text at six in the morning.\nInterviewer: What goes wrong?\nJo: Gate codes. Half the time the code in the text is old.\n");
await page.locator('input[type="file"]').first().setInputFiles(".what-build/walkthrough/dispatch.txt");
await page.getByRole("button", { name: "Continue" }).click();
await page.getByRole("button", { name: "Create source" }).click();
await page.waitForURL(/evidence\/[0-9A-Z]{26}/);
step("created a tagged source, taking a tag the product already uses, and uploaded its attachment");
await page.locator(".source-text").getByText("A group text at six in the morning.").waitFor({ timeout: 15000 });
await page.getByText("Read from dispatch.txt").waitFor();
step("the worker read the attachment, and its text became the source's (the page updated itself)");
await page.getByRole("button", { name: "Edit", exact: true }).click();
const editor = page.getByRole("textbox", { name: "Text", exact: true });
await editor.fill((await editor.inputValue()).replace("Half the time", "Half of the time"));
await page.getByRole("button", { name: "Save" }).click();
await page.getByText("Text saved.").waitFor();
await page.getByText(/^Written by /).waitFor();
step("corrected a word in the source's text");
await page.getByRole("button", { name: "Add a summary" }).click();
await page.getByRole("textbox", { name: "Summary" }).fill("Crews learn their day from a 6 a.m. group text, and stale gate codes in it cost time.");
await page.getByRole("button", { name: "Save" }).click();
await page.getByText("Summary saved.").waitFor();
step("wrote the source's summary under its title");
await page.getByRole("link", { name: /^Comments/ }).click();
await page.getByRole("button", { name: "Comment" }).first().click();
await page.getByRole("textbox", { name: "Comment", exact: true }).fill("Stale gate codes again — same as Greenline.");
await page.getByRole("button", { name: "Save comment" }).click();
await page.getByText("Comment added.").waitFor();
step("commented on the source");
await page.goto(`${app}/evidence`);
await page.getByRole("button", { name: /^Search Crewboard/ }).click();
const find = page.getByRole("dialog", { name: "Search Crewboard" });
await find.getByRole("combobox").fill("brightway");
// .first(): a database an earlier run used holds an earlier copy of the source too.
await find.getByRole("option", { name: /Dispatcher interview — Brightway Cleaning/ }).first().waitFor();
await page.keyboard.press("Escape");
await find.waitFor({ state: "detached" });
step("found the source by its title from the panel's search, then closed it");
await page.getByRole("link", { name: /^interview\s*\d+$/ }).click();
await page.waitForURL(/tags=interview/);
await page.getByRole("link", { name: /Dispatcher interview — Brightway Cleaning/ }).first().waitFor();
step("filtered the list by a tag from the panel");
await page.goto(`${app}/search?q=gate%20code`);
await page.locator(".find-hit").first().waitFor();
const hits = await page.locator(".find-hit").count();
step(`search found ${hits} places that say "gate code"`);
await page.locator('.find-hit[data-kind="text"]').first().click();
await page.waitForURL(/view=text&find=/);
await page.locator("mark.text-find").first().waitFor();
step("a hit opens the source's text with the words marked");
await page.goto(`${app}/activity`);
await page.getByText("commented on").first().waitFor();
step("the activity log shows the comment");
await page.goto(`${app}/settings`);
await page.getByRole("button", { name: "Export this product" }).click();
await page.getByRole("link", { name: /Download/ }).first().waitFor({ timeout: 20000 });
step("exported the product and got a download link");
await browser.close();
if (errors.length) {
  console.log("page errors:\n" + errors.join("\n"));
  process.exit(1);
}
